<?php
/**
 * Collects per-block CSS and adds `dfb-<uid>` + global class names to rendered markup.
 *
 * CSS for the queried post and the active templates is computed up-front and printed in <head>
 * (no flash of unstyled content). Anything rendered later that was not anticipated
 * (query loops, reusable blocks, widgets) is printed in the footer.
 *
 * @package DFBuilder
 */

namespace DFBuilder;

defined( 'ABSPATH' ) || exit;

final class Css_Collector {

	const HANDLE = 'dfb-blocks';

	/** @var array<string,bool> uids already emitted in <head>. */
	private static $printed = array();

	/** @var array<string,string> uid => css discovered during render. */
	private static $late = array();

	/** @var array<int,bool> reusable-block recursion guard. */
	private static $seen_refs = array();

	public function register(): void {
		add_action( 'init', array( $this, 'register_handle' ) );
		add_filter( 'render_block', array( $this, 'render_block' ), 10, 2 );
		add_action( 'wp_enqueue_scripts', array( $this, 'head_css' ), 20 );
		add_action( 'wp_footer', array( $this, 'footer_css' ), 5 );
	}

	public function register_handle(): void {
		wp_register_style( self::HANDLE, false, array( 'dfb-base', Global_Classes::HANDLE ), DFB_VERSION );
	}

	/**
	 * CSS for one parsed block (not its children).
	 *
	 * @param array $block Parsed block.
	 */
	public static function block_css( array $block ): string {
		$dfb = $block['attrs']['dfb'] ?? null;
		if ( ! is_array( $dfb ) || ! Style_Engine::is_valid_uid( $dfb['uid'] ?? null ) || empty( $dfb['styles'] ) ) {
			return '';
		}
		return Style_Engine::generate( '.dfb-' . $dfb['uid'], $dfb['styles'], Settings::breakpoints() );
	}

	/**
	 * Walk a block tree and return uid => css.
	 *
	 * @param array $blocks Parsed blocks.
	 */
	public static function collect( array $blocks ): array {
		$out = array();
		foreach ( $blocks as $block ) {
			if ( empty( $block['blockName'] ) ) {
				continue;
			}
			$css = self::block_css( $block );
			if ( '' !== $css ) {
				$out[ $block['attrs']['dfb']['uid'] ] = $css;
			}
			if ( 'core/block' === $block['blockName'] && ! empty( $block['attrs']['ref'] ) ) {
				$ref = (int) $block['attrs']['ref'];
				if ( empty( self::$seen_refs[ $ref ] ) ) {
					self::$seen_refs[ $ref ] = true;
					$post                    = get_post( $ref );
					if ( $post ) {
						$out += self::collect( parse_blocks( $post->post_content ) );
					}
				}
			}
			if ( ! empty( $block['innerBlocks'] ) ) {
				$out += self::collect( $block['innerBlocks'] );
			}
		}
		return $out;
	}

	public function head_css(): void {
		$sources = Templates::active_posts();
		if ( is_singular() ) {
			$sources[] = get_queried_object();
		}
		$css = array();
		foreach ( $sources as $post ) {
			if ( $post instanceof \WP_Post && has_blocks( $post->post_content ) ) {
				$css += self::collect( parse_blocks( $post->post_content ) );
			}
		}
		wp_enqueue_style( self::HANDLE );
		$css = array_diff_key( $css, self::$printed );
		if ( $css ) {
			self::$printed += array_fill_keys( array_keys( $css ), true );
			wp_add_inline_style( self::HANDLE, implode( '', $css ) );
		}
	}

	public function footer_css(): void {
		if ( self::$late ) {
			echo '<style id="dfb-late-css">' . implode( '', self::$late ) . "</style>\n"; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by Style_Engine from whitelisted values.
		}
	}

	/**
	 * Editor server-side previews (/wp/v2/block-renderer): the editor already applies the
	 * block's classes and CSS to the preview wrapper, so don't add them twice.
	 */
	private static function is_editor_preview(): bool {
		if ( ! defined( 'REST_REQUEST' ) || ! REST_REQUEST ) {
			return false;
		}
		$route = $GLOBALS['wp']->query_vars['rest_route'] ?? '';
		return is_string( $route ) && false !== strpos( $route, '/block-renderer/' );
	}

	/**
	 * @param string $content Rendered block HTML.
	 * @param array  $block   Parsed block.
	 */
	public function render_block( $content, $block ) {
		if ( '' === $content || empty( $block['blockName'] ) || ! Blocks::is_supported( $block['blockName'] ) ) {
			return $content;
		}
		$dfb = $block['attrs']['dfb'] ?? null;
		if ( ! is_array( $dfb ) || self::is_editor_preview() ) {
			return $content;
		}

		$classes = array();
		$uid     = $dfb['uid'] ?? null;
		if ( Style_Engine::is_valid_uid( $uid ) ) {
			$classes[] = 'dfb-' . $uid;
			if ( empty( self::$printed[ $uid ] ) && ! isset( self::$late[ $uid ] ) ) {
				$css = self::block_css( $block );
				if ( '' !== $css ) {
					if ( did_action( 'wp_head' ) ) {
						self::$late[ $uid ] = $css;
					} else {
						// Rendered before <head> was printed (e.g. block themes): attach to head.
						self::$printed[ $uid ] = true;
						wp_add_inline_style( self::HANDLE, $css );
					}
				}
			}
		}
		foreach ( Global_Classes::names_for( (array) ( $dfb['classes'] ?? array() ) ) as $name ) {
			$classes[] = $name;
		}
		if ( ! $classes ) {
			return $content;
		}

		$p = new \WP_HTML_Tag_Processor( $content );
		if ( $p->next_tag() ) {
			foreach ( $classes as $class ) {
				$p->add_class( $class );
			}
			return $p->get_updated_html();
		}
		return $content;
	}
}
