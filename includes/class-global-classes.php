<?php
/**
 * Global (reusable) classes, Oxygen "selectors" style.
 *
 * Stored in one option as a list of { id, name, styles }. Blocks reference classes by id so
 * renaming a class never breaks markup. Compiled to uploads/df-builder/classes.css.
 *
 * @package DFBuilder
 */

namespace DFBuilder;

defined( 'ABSPATH' ) || exit;

final class Global_Classes {

	const OPTION      = 'dfb_classes';
	const VERSION_OPT = 'dfb_classes_version';
	const HANDLE      = 'dfb-classes';
	const CAP         = 'edit_theme_options';
	const NS          = 'dfb/v1';

	public function register(): void {
		add_action( 'rest_api_init', array( $this, 'routes' ) );
		add_action( 'init', array( $this, 'register_style' ) );
		add_action( 'wp_enqueue_scripts', array( $this, 'enqueue' ), 15 );
	}

	/** @return array<int,array{id:string,name:string,styles:array}> */
	public static function all(): array {
		$list = get_option( self::OPTION, array() );
		return is_array( $list ) ? array_values( $list ) : array();
	}

	/**
	 * Map class ids → class names (unknown ids dropped).
	 *
	 * @param array $ids Class ids.
	 */
	public static function names_for( array $ids ): array {
		static $map = null;
		if ( null === $map ) {
			$map = array();
			foreach ( self::all() as $c ) {
				$map[ $c['id'] ] = $c['name'];
			}
		}
		$out = array();
		foreach ( $ids as $id ) {
			if ( is_string( $id ) && isset( $map[ $id ] ) ) {
				$out[] = $map[ $id ];
			}
		}
		return $out;
	}

	public static function css(): string {
		$bps = Settings::breakpoints();
		$css = '';
		foreach ( self::all() as $c ) {
			if ( Style_Engine::is_valid_class_name( $c['name'] ?? null ) ) {
				$css .= Style_Engine::generate( '.' . $c['name'], $c['styles'] ?? array(), $bps );
			}
		}
		return $css;
	}

	private static function paths(): array {
		$up = wp_upload_dir( null, false );
		return array(
			'dir' => trailingslashit( $up['basedir'] ) . 'df-builder',
			'url' => trailingslashit( $up['baseurl'] ) . 'df-builder',
		);
	}

	/**
	 * Write classes.css. Falls back to inline output if the uploads dir is not writable.
	 */
	public static function compile(): bool {
		$paths = self::paths();
		$ok    = wp_mkdir_p( $paths['dir'] );
		if ( $ok ) {
			// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents
			$ok = false !== file_put_contents( $paths['dir'] . '/classes.css', "/* Generated by DF Builder. Do not edit. */\n" . self::css() );
		}
		update_option( self::VERSION_OPT, $ok ? (string) time() : 'inline', false );
		return $ok;
	}

	public function register_style(): void {
		$version = get_option( self::VERSION_OPT, '' );
		$paths   = self::paths();
		if ( $version && 'inline' !== $version && file_exists( $paths['dir'] . '/classes.css' ) ) {
			wp_register_style( self::HANDLE, $paths['url'] . '/classes.css', array( 'dfb-base' ), $version );
		} else {
			wp_register_style( self::HANDLE, false, array( 'dfb-base' ), DFB_VERSION );
			wp_add_inline_style( self::HANDLE, self::css() );
		}
	}

	public function enqueue(): void {
		if ( self::all() ) {
			wp_enqueue_style( self::HANDLE );
		}
	}

	/* ---------------------------------------------------------------- REST */

	public function routes(): void {
		$can_read  = static fn() => current_user_can( 'edit_posts' );
		$can_write = static fn() => current_user_can( self::CAP );

		register_rest_route(
			self::NS,
			'/classes',
			array(
				array(
					'methods'             => 'GET',
					'callback'            => static fn() => rest_ensure_response( self::all() ),
					'permission_callback' => $can_read,
				),
				array(
					'methods'             => 'POST',
					'callback'            => array( $this, 'create' ),
					'permission_callback' => $can_write,
					'args'                => array(
						'name'   => array(
							'type'     => 'string',
							'required' => true,
						),
						'styles' => array( 'type' => 'object' ),
					),
				),
			)
		);
		register_rest_route(
			self::NS,
			'/classes/(?P<id>c[a-z0-9]{4,16})',
			array(
				array(
					'methods'             => 'PUT, PATCH',
					'callback'            => array( $this, 'update' ),
					'permission_callback' => $can_write,
				),
				array(
					'methods'             => 'DELETE',
					'callback'            => array( $this, 'delete' ),
					'permission_callback' => $can_write,
				),
			)
		);
	}

	private static function save( array $list ): void {
		update_option( self::OPTION, array_values( $list ), true );
		self::compile();
	}

	private static function name_taken( array $list, string $name, string $except_id = '' ): bool {
		foreach ( $list as $c ) {
			if ( $c['name'] === $name && $c['id'] !== $except_id ) {
				return true;
			}
		}
		return false;
	}

	public function create( \WP_REST_Request $req ) {
		$name = trim( (string) $req['name'] );
		if ( ! Style_Engine::is_valid_class_name( $name ) ) {
			return new \WP_Error( 'dfb_invalid_name', __( 'Class names must start with a letter and contain only letters, numbers, - and _.', 'df-builder' ), array( 'status' => 400 ) );
		}
		$list = self::all();
		if ( self::name_taken( $list, $name ) ) {
			return new \WP_Error( 'dfb_name_taken', __( 'A class with that name already exists.', 'df-builder' ), array( 'status' => 409 ) );
		}
		$class  = array(
			'id'     => 'c' . strtolower( wp_generate_password( 8, false, false ) ),
			'name'   => $name,
			'styles' => Style_Engine::clean( $req['styles'] ?? array() ),
		);
		$list[] = $class;
		self::save( $list );
		return rest_ensure_response( $class );
	}

	public function update( \WP_REST_Request $req ) {
		$list = self::all();
		foreach ( $list as $i => $c ) {
			if ( $c['id'] !== $req['id'] ) {
				continue;
			}
			if ( isset( $req['name'] ) ) {
				$name = trim( (string) $req['name'] );
				if ( ! Style_Engine::is_valid_class_name( $name ) || self::name_taken( $list, $name, $c['id'] ) ) {
					return new \WP_Error( 'dfb_invalid_name', __( 'Invalid or duplicate class name.', 'df-builder' ), array( 'status' => 400 ) );
				}
				$list[ $i ]['name'] = $name;
			}
			if ( isset( $req['styles'] ) ) {
				$list[ $i ]['styles'] = Style_Engine::clean( $req['styles'] );
			}
			self::save( $list );
			return rest_ensure_response( $list[ $i ] );
		}
		return new \WP_Error( 'dfb_not_found', __( 'Class not found.', 'df-builder' ), array( 'status' => 404 ) );
	}

	public function delete( \WP_REST_Request $req ) {
		$list = self::all();
		$new  = array_filter( $list, static fn( $c ) => $c['id'] !== $req['id'] );
		if ( count( $new ) === count( $list ) ) {
			return new \WP_Error( 'dfb_not_found', __( 'Class not found.', 'df-builder' ), array( 'status' => 404 ) );
		}
		self::save( $new );
		return rest_ensure_response( array( 'deleted' => true ) );
	}
}
